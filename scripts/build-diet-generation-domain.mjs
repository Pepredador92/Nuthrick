// Same shared-domain bundling convention as build-workshop-ai-engine.mjs.
// No handler imports this module yet; no provider code is bundled.
import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const require = createRequire(new URL('../frontend/package.json', import.meta.url));
const { build } = require('esbuild');
const outfile = fileURLToPath(new URL('../supabase/functions/ai/diet-generation-domain.js', import.meta.url));
const check = process.argv.includes('--check');
const result = await build({ entryPoints: [fileURLToPath(new URL('../frontend/src/features/diet-workshop/generationBoundary.ts', import.meta.url))],
  outfile, bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', write: !check,
  alias: { '@/src': fileURLToPath(new URL('../frontend/src', import.meta.url)) },
  banner: { js: '// GENERATED by scripts/build-diet-generation-domain.mjs. Offline domain only; no handler/provider integration.' } });
if (check && await readFile(outfile,'utf8') !== result.outputFiles[0].text) throw Error('Diet generation domain bundle is stale');
